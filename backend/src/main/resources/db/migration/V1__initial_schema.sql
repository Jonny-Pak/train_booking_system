-- PostgreSQL 16+ / Flyway V1__initial_schema.sql
-- Create database outside this migration: CREATE DATABASE ticket_booking;
-- Timestamps are stored in UTC as TIMESTAMPTZ.
 
CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 phone VARCHAR(20),
 role VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER' CHECK (role IN ('CUSTOMER','ADMIN')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE routes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 origin VARCHAR(160) NOT NULL,
 destination VARCHAR(160) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT chk_route_different CHECK (origin <> destination)
);
CREATE TABLE vehicles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vehicle_code VARCHAR(40) NOT NULL UNIQUE,
 vehicle_type VARCHAR(10) NOT NULL CHECK (vehicle_type IN ('BUS','TRAIN')),
 display_name VARCHAR(120) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE seats (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
 seat_code VARCHAR(20) NOT NULL,
 seat_class VARCHAR(40) NOT NULL DEFAULT 'STANDARD',
 CONSTRAINT uq_vehicle_seat UNIQUE(vehicle_id,seat_code),
 CONSTRAINT uq_seat_id_vehicle UNIQUE(id,vehicle_id)
);
CREATE TABLE trips (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 route_id BIGINT NOT NULL REFERENCES routes(id),
 vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
 departure_at TIMESTAMPTZ NOT NULL,
 arrival_at TIMESTAMPTZ NOT NULL,
 base_price NUMERIC(12,2) NOT NULL CHECK(base_price >= 0),
 status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED' CHECK(status IN ('SCHEDULED','CANCELLED','COMPLETED')),
 CONSTRAINT uq_trip_vehicle UNIQUE(id,vehicle_id),
 CONSTRAINT chk_trip_time CHECK (arrival_at > departure_at)
);
CREATE INDEX idx_trip_search ON trips(route_id,departure_at,status);
CREATE TABLE bookings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_code VARCHAR(32) NOT NULL UNIQUE,
 user_id BIGINT NOT NULL REFERENCES users(id),
 trip_id BIGINT NOT NULL,
 vehicle_id BIGINT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','PAID','CANCELLED','EXPIRED')),
 hold_expires_at TIMESTAMPTZ NOT NULL,
 total_amount NUMERIC(12,2) NOT NULL CHECK(total_amount >= 0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_booking_trip_vehicle FOREIGN KEY(trip_id,vehicle_id) REFERENCES trips(id,vehicle_id),
 CONSTRAINT uq_booking_trip_vehicle UNIQUE(id,trip_id,vehicle_id)
);
CREATE INDEX idx_booking_expiry ON bookings(status,hold_expires_at);
CREATE TABLE booking_seats (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_id BIGINT NOT NULL,
 trip_id BIGINT NOT NULL,
 vehicle_id BIGINT NOT NULL,
 seat_id BIGINT NOT NULL,
 unit_price NUMERIC(12,2) NOT NULL CHECK(unit_price >= 0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT fk_bs_booking_trip_vehicle FOREIGN KEY(booking_id,trip_id,vehicle_id) REFERENCES bookings(id,trip_id,vehicle_id),
 CONSTRAINT fk_bs_seat_vehicle FOREIGN KEY(seat_id,vehicle_id) REFERENCES seats(id,vehicle_id),
 CONSTRAINT uq_booking_seat UNIQUE(booking_id,seat_id)
);
-- PostgreSQL partial unique index: only active rows reserve seats.
CREATE UNIQUE INDEX uq_active_trip_seat ON booking_seats(trip_id,seat_id) WHERE is_active IS TRUE;
CREATE TABLE payments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_id BIGINT NOT NULL REFERENCES bookings(id),
 txn_ref VARCHAR(100) NOT NULL UNIQUE,
 provider VARCHAR(30) NOT NULL DEFAULT 'VNPAY',
 amount NUMERIC(12,2) NOT NULL CHECK(amount >= 0),
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','SUCCESS','FAILED')),
 provider_transaction_id VARCHAR(100) UNIQUE,
 paid_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tickets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_code VARCHAR(40) NOT NULL UNIQUE,
 booking_seat_id BIGINT NOT NULL UNIQUE REFERENCES booking_seats(id),
 issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
